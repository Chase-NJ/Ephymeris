# --- TypeScript emission ----------------------------------------------------


def ts_type(ty: Ty) -> str:
    if isinstance(ty, Prim):
        return {
            "str": "string",
            "int": "number",
            "float": "number",
            "bool": "boolean",
            "any": "unknown",
            "null": "null",
        }[ty.kind]
    if isinstance(ty, Lit):
        return " | ".join(f'"{v}"' for v in ty.values)
    if isinstance(ty, ListOf):
        item = ts_type(ty.item)
        return f"{item}[]" if " " not in item else f"Array<{item}>"
    if isinstance(ty, MapOf):
        return f"Record<string, {ts_type(ty.value)}>"
    if isinstance(ty, UnionOf):
        return " | ".join(ts_type(o) for o in ty.options)
    if isinstance(ty, Ref):
        return ty.name
    if isinstance(ty, Obj):
        parts = []
        for fld in ty.fields:
            opt = "?" if fld.optional else ""
            parts.append(f"{fld.name}{opt}: {ts_type(fld.ty)}")
        return "{ " + "; ".join(parts) + " }" if parts else "Record<string, never>"
    raise TypeError(f"unknown type node: {ty!r}")


def _ts_doc(doc: str, indent: str = "") -> list[str]:
    if len(doc) <= 96 - len(indent):
        return [f"{indent}/** {doc} */"]
    lines = [f"{indent}/**"]
    words, line = doc.split(), f"{indent} *"
    for word in words:
        if len(line) + len(word) + 1 > 98:
            lines.append(line)
            line = f"{indent} * {word}"
        else:
            line += f" {word}"
    lines.append(line)
    lines.append(f"{indent} */")
    return lines


def _ts_shape(shape: Shape) -> list[str]:
    out: list[str] = []
    if shape.doc:
        out.extend(_ts_doc(shape.doc))
    if isinstance(shape.ty, Obj):
        out.append(f"export interface {shape.name} {{")
        for fld in shape.ty.fields:
            if fld.doc:
                out.extend(_ts_doc(fld.doc, "  "))
            opt = "?" if fld.optional else ""
            out.append(f"  {fld.name}{opt}: {ts_type(fld.ty)};")
        out.append("}")
    else:
        out.append(f"export type {shape.name} = {ts_type(shape.ty)};")
    out.append("")
    return out


def emit_ts(protocol: Protocol) -> str:
    lines: list[str] = []
    push = lines.append

    push("/**")
    push(" * Canonical wire protocol between this frontend and the Python sidecar.")
    push(" *")
    for note_line in GENERATED_NOTE.split("\n"):
        push(f" * {note_line}")
    push(" *")
    push(" * `docs/websocket-protocol.md` carries the prose (rationale, lifecycle,")
    push(" * invariants); `protocol/schema.py` is the shape authority this file and")
    push(" * `sidecar/ephymeris_sidecar/protocol.py` are generated from.")
    push(" */")
    push("")
    push(f"export const PROTOCOL_VERSION = {protocol.version};")
    push("")

    push("// --- Commands (client -> server) -------------------------------------------")
    push("")
    push("export const CMD = {")
    for cmd in protocol.commands:
        if cmd.section:
            if lines[-1] != "export const CMD = {":
                push("")
            push(f"  // {cmd.section}")
        push(f'  {cmd.const}: "{cmd.name}",')
    push("} as const;")
    push("")
    push("export type CommandName = (typeof CMD)[keyof typeof CMD];")
    push("")

    push("// --- Events (server -> client) ---------------------------------------------")
    push("")
    push("export const EVT = {")
    for evt in protocol.events:
        push(f'  {evt.const}: "{evt.name}",')
    push("} as const;")
    push("")
    push("export type EventName = (typeof EVT)[keyof typeof EVT];")
    push("")

    push("// --- Error codes -----------------------------------------------------------")
    push("")
    push("export const ERR = {")
    for err in protocol.errors:
        push(f'  {err.name}: "{err.name}",')
    push("} as const;")
    push("")
    push("export type ErrorCode = (typeof ERR)[keyof typeof ERR];")
    push("")

    push("// --- Payload shapes --------------------------------------------------------")
    push("")
    for shape in protocol.shapes:
        lines.extend(_ts_shape(shape))

    push("// --- Per-command and per-event payload maps --------------------------------")
    push("")
    push("/** Args each command takes; `Record<string, never>` = none. */")
    push("export interface CommandArgsMap {")
    for cmd in protocol.commands:
        args = ts_type(cmd.args) if cmd.args is not None else "Record<string, never>"
        push(f'  "{cmd.name}": {args};')
    push("}")
    push("")
    push("/** The `result` field of each command's ok-reply. */")
    push("export interface CommandResultMap {")
    for cmd in protocol.commands:
        push(f'  "{cmd.name}": {ts_type(cmd.result)};')
    push("}")
    push("")
    push("/** The `data` field of each event. */")
    push("export interface EventDataMap {")
    for evt in protocol.events:
        push(f'  "{evt.name}": {ts_type(evt.data)};')
    push("}")
    push("")

    push(TS_STATIC_TAIL.rstrip("\n"))
    push("")
    return "\n".join(lines)


