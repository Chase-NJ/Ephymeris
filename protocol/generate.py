# --- Python emission --------------------------------------------------------


def py_spec(ty: Ty):
    """The runtime spec encoding `validate()` walks — nested tuples/strings."""
    if isinstance(ty, Prim):
        return ty.kind
    if isinstance(ty, Lit):
        return ("lit", tuple(ty.values))
    if isinstance(ty, ListOf):
        return ("list", py_spec(ty.item))
    if isinstance(ty, MapOf):
        return ("map", py_spec(ty.value))
    if isinstance(ty, UnionOf):
        return ("union", tuple(py_spec(o) for o in ty.options))
    if isinstance(ty, Ref):
        return ("ref", ty.name)
    if isinstance(ty, Obj):
        return ("obj", tuple((fld.name, py_spec(fld.ty), fld.optional) for fld in ty.fields))
    raise TypeError(f"unknown type node: {ty!r}")


