def bundled_pins_h(sketch_name: str) -> str:
    """This rig's pins, for a BUNDLED sketch that asked to be rebuilt.

    Pins only. A bundled sketch has no trial table, no ramp and no selection
    mode — those are what a task PROFILE adds — and emitting counts it does not
    use would be inventing a shape for it.

    NO STROBE OVERRIDES EITHER, though `task_pins_h` emits them. A profile can
    reference a code the app added after the firmware was built; a bundled
    sketch only ever references codes its own `BoxStrobes.h` defines, and those
    two are pinned to each other by `tests/test_taskdef.py`. A second source for
    the same numbers would buy nothing and could disagree.
    """
    channels = registry.channels()
    lines = [
        "/*  GENERATED by Ephymeris -- do not edit.",
        "",
        "    A rebuild of the bundled sketch against THIS RIG'S wiring, served in",
        "    place of the one that ships. Rewritten whenever the wiring changes;",
        "    an edit here is lost at the next change without a word.",
        "",
        f"    Sketch:  {sketch_name}",
        f"    Wiring:  {channels.pinout_id} ({channels.content_hash()})",
        "*/",
        "",
        "#ifndef TASK_PINS_H",
        "#define TASK_PINS_H",
        "",
        "/*  Every one of these overrides a guarded default in BoxPins.h. A channel",
        "    the rig does not declare is simply not mentioned and keeps the shipped",
        "    number, so a partial wiring document degrades one pin at a time. */",
    ]
    for name, macro in _PIN_MACROS:
        channel = channels.get(name)
        if channel is not None:
            lines.append(f"#define {macro} {channel.index}")
    lines += _sync_lines(channels)

    # Declaration order, not pin order: `Odors[i]` is odor line i+1 and the pins
    # are not monotonic past line 6. See `declared_of_kind`.
    emitters = channels.declared_of_kind("emitter")
    rewards = channels.declared_of_kind("reward")
    if emitters:
        lines.append(f"#define BOX_NUM_ODORS {len(emitters)}")
        lines.append(
            "#define BOX_ODOR_PINS {" + ", ".join(str(c.index) for c in emitters) + "}"
        )
    if rewards:
        lines.append(f"#define BOX_NUM_FLUIDS {len(rewards)}")
        lines.append(
            "#define BOX_FLUID_PINS {" + ", ".join(str(c.index) for c in rewards) + "}"
        )

    lines += ["", "#endif // TASK_PINS_H", ""]
    return "\n".join(lines)


def task_pins_h(definition: TaskDefinition) -> str:
    """The preprocessor half: pins, strobe codes, counts, selection mode.

    Included BEFORE `<BehaviorBox.h>`, whose `BoxPins.h`/`BoxStrobes.h` guard
    every definition — so what is written here wins and everything unmentioned
    falls back to the box as built. It may not name a type: at the point it is
    read, `TrialType` does not exist yet.
    """
    channels = registry.channels()
    vocab = registry.vocabulary()
    lines: list[str] = [_banner(definition), "", "#ifndef TASK_PINS_H", "#define TASK_PINS_H", ""]

    lines += [
        "/*  This rig's wiring. Every one of these overrides a guarded default in",
        "    BoxPins.h; a channel the rig does not declare is simply not mentioned",
        "    and keeps the shipped number. */",
    ]
    for name, macro in _PIN_MACROS:
        channel = channels.get(name)
        if channel is not None:
            lines.append(f"#define {macro} {channel.index}")
    lines += _sync_lines(channels)

    # DECLARATION order, not pin order. `Odors[i]` is odor line i+1, and the
    # pins are not monotonic past line 6 -- sorting by pin would put line 7
    # second and silently swap ten of the twelve lines.
    emitters = channels.declared_of_kind("emitter")
    rewards = channels.declared_of_kind("reward")
    if emitters:
        lines.append(f"#define BOX_NUM_ODORS {len(emitters)}")
        lines.append(
            "#define BOX_ODOR_PINS {" + ", ".join(str(c.index) for c in emitters) + "}"
        )
    if rewards:
        lines.append(f"#define BOX_NUM_FLUIDS {len(rewards)}")
        lines.append(
            "#define BOX_FLUID_PINS {" + ", ".join(str(c.index) for c in rewards) + "}"
        )

    lines += [
        "",
        "/*  The onset code each declared stimulus announces itself with, taken",
        "    from the app's append-only vocabulary and named by that vocabulary's",
        "    own name. BoxStrobes.h ships the same numbers, so these normally",
        "    agree exactly; emitting them anyway is what carries a code ADDED in",
        "    the app to firmware that predates it. Never derived from an odor",
        "    index -- the onsets run 101-109 and then 114-116, because 110-113",
        "    are retired codes a recorded session contains. */",
    ]
    for name in sorted({t.onset_strobe for t in definition.trials}):
        entry = vocab.get(name)
        if entry is not None:
            lines.append(f"#define BF_{name} {entry.code}")

    stage_keys = " ".join(f"P_STAGE({i})" for i in range(definition.stage_count))
    lines += [
        "",
        "/*  How many ramp rows exist, and which of them the START grammar can",
        "    reach. The two must agree: a key list longer than the count writes",
        "    past the end of stage[]. */",
        f"#define NUM_STAGES {definition.stage_count}",
        f"#define BOX_STAGE_KEY_LIST {stage_keys}",
        "",
        "/*  How many trial types the table declares, and the two per-type key",
        "    lists -- pool weights and reward volumes, one of each per slot.",
        "    Same pairing rule as the ramp: the count sizes both arrays. */",
        f"#define BOX_MAX_TRIAL_TYPES {max(1, definition.trial_count)}",
    ]
    pool_keys = [
        f'P_INT("PW{i + 1}", poolWeights[{i}])' for i in range(definition.trial_count)
    ]
    # Every slot, go and no-go alike, so the list pairs with the count exactly
    # as the pool list does. task.json declares a field only for go rows; a
    # slot the line never names keeps the 0 compiled into its TrialType.
    reward_keys = [
        f'P_INT("{fields.REWARD_WIRE_KEY}{i + 1}", rewardTimes[{i}])'
        for i in range(definition.trial_count)
    ]
    if pool_keys:
        lines.append("#define BOX_POOL_KEY_LIST " + " ".join(pool_keys))
        lines.append("#define BOX_REWARD_KEY_LIST " + " ".join(reward_keys))
    else:
        # An empty macro rather than none: both lists are referenced
        # unconditionally by TASK_PARAM_LIST, and leaving them to the guarded
        # defaults would declare four slots for a table with no rows.
        lines.append("#define BOX_POOL_KEY_LIST")
        lines.append("#define BOX_REWARD_KEY_LIST")

    mode = _SELECTION_MACRO[definition.selection_mode]
    lines += [
        "",
        "/*  Which selector the loop runs. Anti-bias draws a side against the",
        "    animal's recent expressed bias and then a type from that side",
        "    uniformly; weighted draws the side the same way and the type by",
        "    poolWeights; the pool draws a block-shuffled sequence from the",
        "    weights at START. BehaviorBox.h guards the same three values. */",
        "#define BOX_SELECT_ANTIBIAS 0",
        "#define BOX_SELECT_POOL 1",
        "#define BOX_SELECT_WEIGHTED 2",
        f"#define BOX_SELECTION_MODE {mode}",
        "",
        "#endif // TASK_PINS_H",
        "",
    ]
    return "\n".join(lines)


#: Definition mode -> the firmware macro. A dict rather than a ternary so an
#: unknown mode is a KeyError here, not a silent fall-through to anti-bias.
_SELECTION_MACRO: dict[str, str] = {
    "antibias": "BOX_SELECT_ANTIBIAS",
    "pool": "BOX_SELECT_POOL",
    "weighted": "BOX_SELECT_WEIGHTED",
}


#: Channel name -> the guarded macro in BoxPins.h. Resolution is by KIND for the
#: structural three, so a rig may rename them; the two response ports are named
#: because the trial runner has a left and a right and nothing else.
_PIN_MACROS: tuple[tuple[str, str], ...] = (
    ("odor_port", "BOX_PIN_ODOR_PORT"),
    ("right_well", "BOX_PIN_RIGHT_WELL"),
    ("left_well", "BOX_PIN_LEFT_WELL"),
    ("trial_light", "BOX_PIN_TRIAL_LIGHT"),
    ("vacuum", "BOX_PIN_VACUUM"),
)


def _sync_lines(channels: Any) -> list[str]:
    """`BOX_PIN_SYNC_OUT`, which is the one pin that is ALWAYS emitted.

    Every other pin that the rig does not declare is left unmentioned and keeps
    the number in BoxPins.h, so a partial document degrades one pin at a time.
    That rule is wrong for this line. The shipped default would pulse pin 49 on
    a rig whose operator never declared a sync channel -- and may have put
    something else there -- while the app, reading the same document, reports
    that the box has no sync line. So absence is stated: -1 compiles the pulse
    out, and the header and the app cannot disagree.

    Resolved by KIND, like the engagement port: it is a structural fact of the
    box and no task names it. Two sync channels (RIG105) resolve to none.
    """
    sync = channels.unique_of_kind("sync")
    return [
        "/*  One pulse per strobe, into a recording controller's digital input.",
        "    -1 = this rig declares no sync channel; the pulse is compiled out. */",
        f"#define BOX_PIN_SYNC_OUT {sync.index if sync is not None else -1}",
    ]


def _onset_macro(trial: TrialTypeDef) -> str:
    """The C name for this type's onset code.

    A straight `BF_` + the vocabulary's own name, with no arithmetic anywhere.
    An earlier version derived `BF_ODOR_<n>_ON` from the emitter's position and
    was wrong twice over: the position came from a pin-sorted list, and the
    codes are not contiguous anyway -- the onsets run 101-109 and then 114-116,
    with four retired numbers in the gap. What the operator picked is a NAME;
    this passes it through.
    """
    return f"BF_{trial.onset_strobe}"


def task_trials_h(definition: TaskDefinition) -> str:
    """The trial table, constructing `TrialType`. Included AFTER BehaviorBox.h."""
    channels = registry.channels()
    vocab = registry.vocabulary()

    lines: list[str] = [
        _banner(definition),
        "",
        "#ifndef TASK_TRIALS_H",
        "#define TASK_TRIALS_H",
        "",
        "/*  THE ORDER IS THE CONTRACT: slot i is poolWeights[i] (wire key PW<i+1>)",
        "    and rewardTimes[i] (wire key RW<i+1>). Reordering silently re-weights",
        "    a pool task and re-pays every condition, so the app emits this table",
        "    and both key lists from one pass over one list.",
        "",
        "    NOT const: each row's last argument is its reward volume, the",
        "    profile's default, and applyRewardTimes() overwrites it from the",
        "    START line before the first trial. */",
        "static TrialType kTrials[] = {",
    ]

    # Declaration order, matching BOX_ODOR_PINS above: slot i of that table is
    # `Odors[i]`, so the two must be built from the same list.
    emitters = channels.declared_of_kind("emitter")
    for trial in definition.trials:
        odor_index = next(
            (i for i, c in enumerate(emitters) if c.name == trial.odor_channel), None
        )
        onset = _onset_macro(trial)
        if odor_index is None or trial.onset_strobe not in vocab:
            continue

        if trial.is_go:
            port = channels.get(trial.response_channel) if trial.response_channel else None
            reward_index = _reward_index(channels, trial.reward_channel)
            slot = vocab.port_slot(port.port_slot) if port and port.port_slot else None
            if port is None or reward_index is None or not slot:
                continue
            well = "rightWell" if port.name == "right_well" else "leftWell"
            fluid_code = f"BF_{slot['reward_code']}"
            stop_code = f"BF_{slot['reward_stop_code']}"
            label = trial.label or f"{trial.odor_channel} -> {port.name}"
            lines += [
                f"    /* {label} */",
                "    TrialType(true, "
                f"Odors[{odor_index}], {well}, {reward_index}, "
                f"{onset}, {fluid_code}, {stop_code}, {trial.reward_time}),",
            ]
        else:
            label = trial.label or f"{trial.odor_channel} -> withhold"
            lines += [
                f"    /* {label} (no-go: no correct port, no reward) */",
                "    TrialType(false, "
                f"Odors[{odor_index}], {SENTINEL}, {SENTINEL}, {onset}, 0, 0, 0),",
            ]

    lines += [
        "};",
        "",
        "static const int kTrialCount = (int)(sizeof(kTrials) / sizeof(kTrials[0]));",
        "",
        "/*  The table cannot outgrow the arrays that index it -- poolWeights[] and",
        "    the selector's side lists are both BOX_MAX_TRIAL_TYPES long. Emitted",
        "    together, so this only fires on a hand edit; it fires at build time,",
        "    which is the point. */",
        "static_assert(kTrialCount <= BOX_MAX_TRIAL_TYPES,",
        '              "more trial types than BOX_MAX_TRIAL_TYPES");',
        "",
        "#endif // TASK_TRIALS_H",
        "",
    ]
    return "\n".join(lines)


def _reward_index(channels, name: str | None) -> int | None:
    """Position in the DECLARED reward list — the index into `Fluids[]`.

    The same order `BOX_FLUID_PINS` is emitted in, so index and pin describe one
    line by construction rather than by agreement. Declaration order rather than
    pin order for the reason `declared_of_kind` gives: these happen to ascend
    today, and relying on that is how the odor table went wrong.
    """
    if name is None:
        return None
    for i, channel in enumerate(channels.declared_of_kind("reward")):
        if channel.name == name:
            return i
    return None


def _banner(definition: TaskDefinition) -> str:
    channels = registry.channels()
    return _GENERATED_BANNER.format(
        name=definition.name,
        pinout=channels.pinout_id,
        pinout_hash=channels.content_hash(),
    )


def generated_files(definition: TaskDefinition, sketch_source: str) -> dict[str, str]:
    """Everything the sketch folder holds, keyed by filename.

    `sketch_source` is the root `GRGL.ino` read from the bundled library — copied
    rather than templated, so there is one trial runner and one session loop in
    the world and a profile cannot fork them.
    """
    name = definition.name
    return {
        f"{name}.ino": sketch_source,
        "TaskPins.h": task_pins_h(definition),
        "TaskTrials.h": task_trials_h(definition),
        "task.json": json.dumps(profile_json(definition), indent=2) + "\n",
    }
