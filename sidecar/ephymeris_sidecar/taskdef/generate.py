"""A task definition + this rig's wiring -> a compilable sketch folder.

Four files, and which of them a value lands in is decided by whether it fits on
a `START` line (`TASKS.md#two-places-a-value-can-come-from`):

    <name>.ino      the root GRGL sketch, copied verbatim from the bundle
    TaskPins.h      pins, strobe codes, counts, selection mode  (preprocessor)
    TaskTrials.h    the trial table                             (needs TrialType)
    task.json       the profile the app itself reads

NOTHING HERE INVENTS A VALUE. Every pin comes from the composed channel map,
every strobe code from the vocabulary, every field label from `fields.py`, and
every number from the definition or that catalogue's default. A defaults table
in this file would be a second answer to a question the registries already
answer, which is exactly the mirroring the whole arrangement exists to end.

THE GENERATED FOLDER IS A BUILD OUTPUT. It is rewritten whole on every save and
on every `hardware.save`, because a wiring change moves pins the headers carry.
Nothing may be hand-edited there and survive.
"""

from __future__ import annotations

import json
from typing import Any

from ..rig import registry
from ..tasks import profile as task_profile
from . import fields
from .model import TaskDefinition, TrialTypeDef

#: `TrialType`'s no-go sentinel, mirrored from BehaviorBox.h. A no-go type has
#: no correct port and no reward index, and -1 is what the runner tests against.
SENTINEL = "SENTINEL"

_GENERATED_BANNER = (
    "/*  GENERATED by Ephymeris -- do not edit.\n"
    "\n"
    "    Rewritten whole every time this task profile is saved, and again\n"
    "    whenever the rig's wiring changes, because the pin numbers below come\n"
    "    from that wiring. Edit the profile on the Task tab, or the wiring on\n"
    "    the Rig tab; an edit here is lost at the next save without a word.\n"
    "\n"
    "    Task:    {name}\n"
    "    Wiring:  {pinout} ({pinout_hash})\n"
    "*/\n"
)


