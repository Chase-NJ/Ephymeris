"""Generate both wire-protocol mirrors from `schema.py`.

    python protocol/generate.py            # (re)write both mirrors
    python protocol/generate.py --check    # exit 1 if either committed mirror is stale

Emits:
    sidecar/ephymeris_sidecar/protocol.py  — names, envelope builders, runtime
                                             shape specs + validator
    src/lib/ws/protocol.ts                 — names, payload types, per-command
                                             args/result maps, envelope types

Stdlib-only on purpose: this must run from a bare interpreter (≥ 3.9) so the
frontend build can invoke it without the sidecar venv existing yet.
"""

